export enum AccountStatus {

  // Аккаунт готов к работе
  Active = 0,
  Cooldown = 1,
  // Аккаунт временно занят парсером (используется как мягкая блокировка)
  InWork = 2,

  // Аккаунт получил бан или неверный пароль
  Banned = 3,

  // Аккаунт на "отлежке" (пауза после работы, чтобы не словить бан)
  Resting = 4,

  // Капча (Желтый)
  CaptchaRequired = 5,
  // Требует подтверждения ( почта или телефон)
  VerificationRequired = 6
}
